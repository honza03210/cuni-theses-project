export const dicts: Record<Locale, Dict> = { cs, en };
export type Key = keyof Dict;

export function fmt(locale: Locale) {
  const tag = locale === 'cs' ? 'cs-CZ' : 'en-GB';
  const cache = new Map<string, Intl.NumberFormat>();
  const nf = (o: Intl.NumberFormatOptions) => {
    const k = JSON.stringify(o);
    let f = cache.get(k);
    if (!f) { f = new Intl.NumberFormat(tag, o); cache.set(k, f); }
    return f;
  };
  return {
    int: (v: number) => nf({ maximumFractionDigits: 0 }).format(v),
    num: (v: number, d = 2) => nf({ minimumFractionDigits: d, maximumFractionDigits: d }).format(v),
    pct: (v: number, d = 1) => nf({ style: 'percent', minimumFractionDigits: d, maximumFractionDigits: d }).format(v),
    signed: (v: number, d = 2) => nf({ minimumFractionDigits: d, maximumFractionDigits: d, signDisplay: 'exceptZero' }).format(v),
  };
}
